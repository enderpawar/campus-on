-- 명세 v0.1 §6 초안 기반 임시 스키마. 확정 ERD(김유빈)로 교체 예정: docs/erd-handoff.md 참고
CREATE TABLE school (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  lms_base_url VARCHAR(255) NOT NULL,
  CONSTRAINT uq_school_name UNIQUE (name),
  CONSTRAINT ck_school_name_not_blank CHECK (name <> '')
);
CREATE TABLE member (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id BIGINT NOT NULL,
  email VARCHAR(255) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  name VARCHAR(50) NOT NULL,
  department VARCHAR(100),
  grade INT,
  token_version INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_member_school FOREIGN KEY (school_id) REFERENCES school (id),
  CONSTRAINT uq_member_email UNIQUE (email),
  CONSTRAINT ck_member_name_not_blank CHECK (name <> ''),
  CONSTRAINT ck_member_grade CHECK (grade BETWEEN 1 AND 6)
);
CREATE TABLE event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL,
  type VARCHAR(20) NOT NULL,
  source VARCHAR(20) NOT NULL,
  title VARCHAR(200) NOT NULL,
  place VARCHAR(100),
  starts_at TIMESTAMP(6) WITH TIME ZONE,
  due_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  done BOOLEAN NOT NULL DEFAULT FALSE,
  external_uid VARCHAR(200),
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_event_member FOREIGN KEY (member_id) REFERENCES member (id),
  CONSTRAINT ck_event_type CHECK (type IN ('ASSIGNMENT', 'LECTURE', 'EXAM', 'PERSONAL')),
  CONSTRAINT ck_event_source CHECK (source IN ('ECLASS', 'PERSONAL')),
  CONSTRAINT ck_event_title_not_blank CHECK (title <> ''),
  CONSTRAINT ck_event_time_order CHECK (starts_at IS NULL OR starts_at < due_at),
  CONSTRAINT uq_event_external UNIQUE (member_id, source, external_uid)
);
CREATE INDEX ix_event_member_due ON event (member_id, due_at);
CREATE TABLE calendar_feed (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL,
  token VARCHAR(64) NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_calendar_feed_member FOREIGN KEY (member_id) REFERENCES member (id),
  CONSTRAINT uq_calendar_feed_member UNIQUE (member_id),
  CONSTRAINT uq_calendar_feed_token UNIQUE (token)
);
CREATE TABLE notice (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id BIGINT NOT NULL,
  source VARCHAR(100) NOT NULL,
  category VARCHAR(20) NOT NULL,
  title VARCHAR(200) NOT NULL,
  url VARCHAR(500) NOT NULL,
  summary VARCHAR(500),
  target_grade INT,
  posted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_notice_school FOREIGN KEY (school_id) REFERENCES school (id),
  CONSTRAINT ck_notice_category CHECK (category IN ('ACADEMIC', 'SCHOLARSHIP', 'CAREER', 'EVENT')),
  CONSTRAINT ck_notice_target_grade CHECK (target_grade BETWEEN 1 AND 6),
  CONSTRAINT uq_notice_school_url UNIQUE (school_id, url)
);
CREATE INDEX ix_notice_school_posted ON notice (school_id, posted_at DESC);
