-- Related ERD tables only. school and schedule metadata remain application extensions.
CREATE TABLE courses (
  course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id BIGINT NOT NULL REFERENCES school(id),
  course_type VARCHAR(10) NOT NULL,
  course_name VARCHAR(300) NOT NULL,
  legacy_kjkey VARCHAR(40) NOT NULL,
  course_status VARCHAR(12) NOT NULL DEFAULT 'OPEN',
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT uq_courses_school_kjkey UNIQUE(school_id, legacy_kjkey)
);
CREATE TABLE course_enrollments (
  enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES courses(course_id),
  user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  enrollment_kind VARCHAR(12) NOT NULL,
  enrollment_role VARCHAR(12) NOT NULL DEFAULT 'STUDENT',
  enrollment_status VARCHAR(12) NOT NULL DEFAULT 'ENROLLED',
  source VARCHAR(12) NOT NULL DEFAULT 'SYSTEM',
  external_sync_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_course_enrollment UNIQUE(course_id, user_id)
);
